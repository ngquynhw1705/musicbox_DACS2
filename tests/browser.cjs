/* Run against the isolated test-web container described in README. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8081';
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error' && !m.text().includes('Failed to load resource'))errors.push(m.text());});
  let checks=0;
  async function verify(condition,label) { assert(condition,label);console.log('PASS',label);checks++; }
  async function login(email) {
    await page.locator('[data-click="login"]').first().click();
    await page.locator('#auth-form [name="email"]').fill(email);
    await page.locator('#auth-form [name="password"]').fill('TestMusicBox!123');
    await page.locator('#auth-form button[type=submit]').click();
    await page.locator('.modal').waitFor({state:'hidden'});
  }
  try {
    await page.goto(base);
    await page.locator('.room-card').first().waitFor();
    await verify(await page.locator('h1').innerText().then(t=>t.includes('Ngàn cảm xúc')),'room catalogue rendered');
    await verify(await page.locator('.hero').evaluate(el=>el.getBoundingClientRect().height<400),'hero and icon layout fit desktop');
    await page.locator('[data-click="register"]').click();
    const stamp=Date.now();
    await page.locator('#auth-form [name="name"]').fill('Browser Customer');
    await page.locator('#auth-form [name="phone"]').fill('0901234567');
    await page.locator('#auth-form [name="email"]').fill(`browser${stamp}@test.local`);
    await page.locator('#auth-form [name="password"]').fill('TestMusicBox!123');
    await page.locator('#auth-form button[type=submit]').click();
    await page.locator('.modal').waitFor({state:'hidden'});
    await page.locator('[data-click="book-room"]').first().click();
    await page.locator('#booking-form [name="time"]').fill('12:00');
    await page.locator('#booking-form [name="duration"]').selectOption('60');
    await page.locator('#booking-form button[type=submit]').click();
    await page.locator('.detail-top').waitFor();
    await verify((await page.locator('.detail-top').innerText()).includes('Chờ xác nhận'),'customer creates booking via UI');
    await page.locator('[data-op="deposit"]').click();
    await page.locator('.detail-top .badge.confirmed').waitFor();
    await verify(true,'simulated deposit confirms booking via UI');
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('[data-op="cancel"]').click();
    await page.locator('.detail-top .badge.cancelled').waitFor();
    await verify((await page.locator('.modal-body').innerText()).includes('Hoàn tiền'),'cancellation records visible refund');
    await page.locator('[data-click="close-modal"]').click();
    await page.locator('[data-click="logout"]').click();
    await page.locator('[data-click="login"]').waitFor();
    await login('admin@test.local');
    await page.locator('a[href="#manage"]').click();
    await page.locator('[data-click="edit-room"]').first().waitFor();
    await page.locator('[data-click="edit-room"]').first().click();
    await page.locator('#room-form [name="name"]').fill(`Browser Room ${stamp}`);
    await page.locator('#room-form [name="description"]').fill('Created by browser test');
    await page.locator('#room-form button[type=submit]').click();
    await page.locator('.modal').waitFor({state:'hidden'});
    await verify((await page.locator('#content').innerText()).includes(`Browser Room ${stamp}`),'admin creates room via UI');
    await page.locator('a[href="#services"]').click();
    await page.locator('[data-click="edit-service"]').first().waitFor();
    await page.locator('[data-click="edit-service"]').first().click();
    await page.locator('#service-form [name="name"]').fill(`Browser Tea ${stamp}`);
    await page.locator('#service-form button[type=submit]').click();
    await page.locator('.modal').waitFor({state:'hidden'});
    await verify((await page.locator('#content').innerText()).includes(`Browser Tea ${stamp}`),'admin creates service via UI');
    await page.locator('a[href="#customers"]').click();
    await page.locator('#customer-filter [name="q"]').fill(`browser${stamp}@test.local`);
    await page.locator('#customer-filter button[type=submit]').click();
    await page.waitForFunction(()=>document.querySelectorAll('#customer-list tbody tr').length===1);
    await verify((await page.locator('#customer-list').innerText()).includes('Browser Customer'),'customer search filters by email');
    await page.locator('a[href="#bookings"]').click();
    await page.locator('#booking-list tbody tr').filter({hasText:'Browser Live Studio'}).locator('[data-click="booking-detail"]').click();
    await page.locator('[data-op="checkin"]').click();
    await page.locator('.detail-top .badge.checked_in').waitFor();
    await verify(await page.locator('[data-elapsed]').innerText().then(t=>t.includes('phút')),'staff check-in starts live usage timer');
    await page.locator('#add-service-form button[type=submit]').click();
    await page.locator('[data-click="service-status"][data-status="served"]').click();
    await page.locator('[data-click="service-status"][data-status="served"]').waitFor({state:'hidden'});
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('[data-op="checkout"]').click();
    await page.locator('.detail-top .badge.completed').waitFor();
    await verify((await page.locator('.modal-body').innerText()).includes('Đã tích'),'staff serves services and settles invoice with loyalty reward');
    await page.locator('[data-click="close-modal"]').click();
    await page.locator('a[href="#reports"]').click();
    await page.locator('#report-form').waitFor();
    const downloadPromise=page.waitForEvent('download');
    await page.locator('[data-click="export-report"]').click();
    const download=await downloadPromise;
    await verify(download.suggestedFilename().endsWith('.csv'),'revenue report exports CSV');
    await page.locator('#navigation a[href="#rooms"]').click();
    await page.locator('.room-card').first().waitFor();
    fs.mkdirSync('test-results',{recursive:true});
    await page.screenshot({path:'test-results/desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
    await verify(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile page has no horizontal overflow');
    await page.locator('#menu-toggle').click();
    await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().left>=-1);
    await page.locator('#navigation a[href="#profile"]').click();
    await page.locator('#profile-form').waitFor();
    await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
    await verify(await page.locator('#profile-form [name="name"]').inputValue()==='Admin','mobile navigation opens account page');
    await page.screenshot({path:'test-results/mobile.png',fullPage:true});
    await verify(errors.length===0,'no JavaScript runtime or CSP errors: '+errors.join(', '));
    console.log(`\n${checks} browser checks passed.`);
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1);});
